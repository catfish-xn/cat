// Augments added after the first icon batch (#122): zh_cn tooltip templates and bundled icons. Run from the repo root:
//   node src/presentation/client-tables/augments.mjs           regenerate ../augment-zh.ts (offline)
//   node src/presentation/client-tables/augments.mjs --icons   also download missing icons from the CommunityDragon 14.24
//                                                              mirror into public/assets/s13/augments/ and append manifest rows
//   node src/presentation/client-tables/augments.mjs --check   verify ../augment-zh.ts is current
// Templates: the content's English tooltip is matched exactly in the archived 14.24 en_us string table and the same key is
// read from zh_cn; ability-style @tokens@ must be identical, so the rules' source values fill them unchanged.
import { buildSync } from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import zlib from 'node:zlib';

const RAW = 'src/simulation/content/source/s13-14.24b/raw/';
const OUT = 'src/presentation/augment-zh.ts', MANIFEST = 'src/presentation/s13-augment-asset-manifest.ts';
const gunzip = file => JSON.parse(zlib.gunzipSync(fs.readFileSync(RAW + file)));
const en = gunzip('en_us.tft.stringtable.json.gz').entries, zh = gunzip('zh_cn.tft.stringtable.json.gz').entries;
const clientItems = new Map(gunzip('en_us.json.gz').items.map(item => [item.apiName, item]));
const bundled = buildSync({ stdin: { contents: [
  "export { AUGMENT_DEFINITIONS } from './src/simulation/content/augments';",
  "export { S13_P2_SOURCE } from './src/simulation/content/s13-augments-p2-source';",
  "export { S13_P3_SOURCE } from './src/simulation/content/s13-p3-source';",
  "export { S13_AUGMENT_ASSETS } from './src/presentation/s13-augment-asset-manifest';"].join('\n'), resolveDir: '.', loader: 'ts' },
  bundle: true, write: false, format: 'esm', platform: 'node' }).outputFiles[0].text;
const { AUGMENT_DEFINITIONS, S13_P2_SOURCE, S13_P3_SOURCE, S13_AUGMENT_ASSETS } = await import('data:text/javascript;base64,' + Buffer.from(bundled).toString('base64'));

/** Client apiNames of the content augments whose source tables do not carry one (looked up by the zh_cn client name). */
const API_NAMES = {
  'blinding-speed': 'TFT9_Augment_BlindingSpeed', 'portable-forge': 'TFT6_Augment_PortableForge', 'radiant-relics': 'TFT6_Augment_RadiantRelics',
  'going-long': 'TFT10_Augment_GoingLong', 'hedge-fund': 'TFT9_Augment_HedgeFund', 'investment-strategy-ii': 'TFT_Augment_InvestmentStrategy2',
};
const apiNameOf = id => S13_P2_SOURCE[id]?.apiName ?? S13_P3_SOURCE[id]?.apiName ?? API_NAMES[id];
const tokens = text => [...new Set((text.match(/@[^@<>\s]+@/g) ?? []).map(token => token.toLowerCase()))].sort().join(' ');
const problems = [];

// zh templates for P3 augments (their content description is the English client string).
const templates = {};
for (const [id, source] of Object.entries(S13_P3_SOURCE)) {
  if (source.kind !== 'augment' || !Object.hasOwn(AUGMENT_DEFINITIONS, id)) continue;
  const key = Object.keys(en).find(k => /^tft_augment_/.test(k) && en[k] === source.description);
  if (!key || !zh[key]) { problems.push(`${id}: no client tooltip`); continue; }
  if (tokens(zh[key]) !== tokens(source.description)) { problems.push(`${id}: token mismatch ${key}`); continue; }
  templates[id] = zh[key].replace(/<br\s*\/?>\s*$/i, '');
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const output = `/**
 * GENERATED by src/presentation/client-tables/augments.mjs from the archived 14.24 en_us / zh_cn string tables. Do not edit.
 * Augment id -> zh_cn client tooltip template for the P3 augments, whose content description is the English client string.
 * Tokens are the English template's (case-insensitive, \`*100\` = source fraction shown as a percent); the rules' source values
 * fill them in augment-display.ts.
 */
export const AUGMENT_ZH_TEMPLATES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(templates, null, 2)});
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(OUT, 'utf8') !== output) { console.error(`${OUT} is stale`); process.exit(1); }
} else fs.writeFileSync(OUT, output);
console.log(`${Object.keys(templates).length} templates, gzip ${zlib.gzipSync(output, { level: 9 }).length} B`);

if (process.argv.includes('--icons')) {
  const have = new Set(S13_AUGMENT_ASSETS.map(asset => asset.id)), rows = [];
  for (const id of Object.keys(AUGMENT_DEFINITIONS).filter(id => !have.has(id))) {
    const apiName = apiNameOf(id), icon = clientItems.get(apiName)?.icon;
    if (!icon) { console.error(`${id}: no client icon (${apiName ?? 'no apiName'})`); continue; }
    const source = `https://raw.communitydragon.org/14.24/game/${icon.toLowerCase().replace(/\.(tex|dds)$/, '.png')}`;
    // Cache-busting query: CommunityDragon's CDN may otherwise answer with a recompressed copy (see the manifest header).
    const response = await fetch(`${source}?orig=${Date.now()}`);
    const bytes = Buffer.from(await response.arrayBuffer()), polished = response.headers.get('cf-polished');
    if (!response.ok || bytes.subarray(0, 4).toString('hex') !== '89504e47') { console.error(`${id}: download failed ${response.status} ${source}`); continue; }
    if (polished && !polished.includes(`orig_size=${bytes.length}`) && /orig_size=/.test(polished)) { console.error(`${id}: recompressed copy (${polished})`); continue; }
    const path = `assets/s13/augments/${id}.png`;
    fs.writeFileSync(`public/${path}`, bytes);
    rows.push({ apiName, id, path, source, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  if (rows.length) {
    const text = fs.readFileSync(MANIFEST, 'utf8'), end = text.lastIndexOf('\n];');
    const added = rows.map(row => JSON.stringify(row, null, 2).replace(/^/gm, '  ')).join(',\n');
    fs.writeFileSync(MANIFEST, `${text.slice(0, end)},\n${added}${text.slice(end)}`);
  }
  console.log(`${rows.length} icons added`);
}
