function git(args) { try { return execFileSync('git', args, { encoding: 'utf8' }).trim(); } catch { return null; } }
function environment() {
  const { sourceFingerprint } = require('./m5-evidence.cjs');
  const cpus = os.cpus();
  return { gitSha: git(['rev-parse', 'HEAD']), gitDirty: git(['status', '--porcelain']), node: process.version, platform: `${process.platform}-${process.arch}`,
    cpuCount: cpus.length, cpuModel: cpus[0]?.model ?? null, memoryBytes: os.totalmem(), loadAverageAtStart: os.loadavg(),
    playwright: require('playwright/package.json').version, vite: require('vite/package.json').version, sourceFingerprint: sourceFingerprint() };
}

async function main() {
  if (OPTIONS.child === 'domain') {
    const result = await domainChild();
    fs.mkdirSync(OUTPUT, { recursive: true });
    fs.writeFileSync(path.join(OUTPUT, 'domain.json'), JSON.stringify(result, null, 2));
    return;
  }
  const started = new Date();
  fs.mkdirSync(OUTPUT, { recursive: true });
  const formal = OPTIONS.seeds === FORMAL.seeds && OPTIONS.pressureReps === FORMAL.pressureReps && OPTIONS.browserWindowMs === FORMAL.browserWindowMs && OPTIONS.part === 'all';
  const manifest = { kind: 'm8-performance', plan: 'M8_PLAN.md §7.6', blocking: false, strict: OPTIONS.strict, formal,
    options: { ...OPTIONS, child: undefined }, environment: environment(), startedAt: started.toISOString(), budgets: BUDGETS,
    fullRunSeeds: FULL_RUNS.slice(0, OPTIONS.seeds), pressureVariants: PRESSURE_VARIANTS, metrics: [], recorded: {}, errors: [] };
  const write = () => fs.writeFileSync(path.join(OUTPUT, 'manifest.json'), JSON.stringify(manifest, null, 2));
  if (OPTIONS.part !== 'browser') {
    try {
      const domain = await runDomainChild();
      manifest.domain = { durationMs: domain.durationMs, gcExposed: domain.gcExposed, warmUp: domain.warmUp, timedRegion: domain.timedRegion,
        pressureSpecSha256: domain.pressureSpecSha256, evidence: 'domain.json' };
      manifest.metrics.push(judge('domain.fullRuns.tickMs', domain.fullRuns.tickMs, BUDGETS.domainTickMs, { routes: domain.fullRuns.routes.length,
        battles: domain.fullRuns.routes.reduce((n, r) => n + r.battles, 0), terminalTickMs: domain.fullRuns.terminalTickMs, worstTicks: domain.fullRuns.worstTicks.slice(0, 5) }));
      for (const variant of PRESSURE_VARIANTS) {
        const p = domain.pressure[variant];
        manifest.metrics.push(judge(`domain.pressure9v9.${variant}.tickMs`, p.tickMs, BUDGETS.domainTickMs, { combats: p.combats.length, fixture: p.fixture }));
      }
      manifest.recorded.domain = { eventsPerBattle: domain.fullRuns.eventsPerBattle, activePeak: domain.fullRuns.activePeak,
        saveEnvelopeBytes: domain.fullRuns.saveEnvelopeBytes, largestBattleRecordBytes: domain.fullRuns.largestBattleRecordBytes,
        nodeHeapUsedPeakBytes: domain.fullRuns.heapUsedPeakBytes, nodeRssPeakBytes: domain.fullRuns.rssPeakBytes,
        pressure: Object.fromEntries(PRESSURE_VARIANTS.map(v => [v, { eventsPerCombat: domain.pressure[v].eventsPerCombat, ticksPerCombat: domain.pressure[v].ticksPerCombat, activePeak: domain.pressure[v].activePeak }])) };
    } catch (error) { manifest.errors.push({ part: 'domain', error: error.stack ?? String(error) }); console.error(error); }
    write();
  }
  if (OPTIONS.part !== 'domain') {
    try {
      const browser = await browserPart();
      fs.writeFileSync(path.join(OUTPUT, 'browser.json'), JSON.stringify(browser, null, 2));
      manifest.environment.chromium = browser.browser;
      manifest.browser = { target: browser.target, segment: browser.segment, durationMs: browser.durationMs, evidence: 'browser.json' };
      for (const mode of ['normal', 'reduced']) {
        const m = browser.modes[mode];
        manifest.metrics.push(judge(`browser.${mode}.frameIntervalMs`, m.frameIntervalMs, BUDGETS.frameIntervalMs, { reducedMotion: m.reducedMotion,
          wholeCombat: m.wholeCombat, segmentMs: m.segmentMs, hiddenIntervals: m.hiddenIntervals, pageErrors: m.errors.length }));
        if (m.errors.length) manifest.errors.push({ part: `browser.${mode}`, error: m.errors.join('\n') });
      }
      manifest.recorded.browser = Object.fromEntries(['normal', 'reduced'].map(mode => { const m = browser.modes[mode];
        return [mode, { combatEvents: m.after.combatEvents, endTick: m.after.tick, importMs: m.importMs, heap: m.heap }]; }));
      manifest.recorded.browser.envelopeBytes = browser.segment.envelopeBytes;
    } catch (error) { manifest.errors.push({ part: 'browser', error: error.stack ?? String(error) }); console.error(error); }
  }
  manifest.environment.loadAverageAtEnd = os.loadavg();
  manifest.endedAt = new Date().toISOString();
  manifest.durationMs = Date.now() - started.getTime();
  manifest.allBudgetsPass = manifest.metrics.length > 0 && manifest.metrics.every(metric => metric.pass);
  write();
  for (const metric of manifest.metrics) console.log(`${metric.pass ? 'PASS' : 'FAIL'} ${metric.id}: n=${metric.count} p50=${metric.p50?.toFixed(3)} p95=${metric.p95?.toFixed(3)} p99=${metric.p99?.toFixed(3)} max=${metric.max?.toFixed(3)} (budget p95<=${metric.threshold.p95}, p99<=${metric.threshold.p99})`);
  console.log(`manifest: ${path.join(OUTPUT, 'manifest.json')}${formal ? '' : ' (non-formal options: smoke evidence only)'}`);
  if (manifest.errors.length) process.exitCode = 1;
  else if (OPTIONS.strict && !manifest.allBudgetsPass) process.exitCode = 1;
}

