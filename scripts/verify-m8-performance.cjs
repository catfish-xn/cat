/** Live mechanism entries on the board (statuses, scheduled tasks, shield layers); diagnostic only. */
function activeEntries(combat) {
  let statuses = 0, tasks = 0, shields = 0;
  for (const unit of combat?.units ?? []) {
    if (!unit.alive) continue;
    statuses += (unit.statuses?.length ?? 0) + (unit.mechanismState?.statuses?.length ?? 0);
    tasks += unit.tasks?.length ?? 0; shields += unit.shieldLayers?.length ?? 0;
  }
  return { statuses, tasks, shields };
}
function peakOf(peak, now) { for (const key of Object.keys(now)) peak[key] = Math.max(peak[key] ?? 0, now[key]); return peak; }
function boardLoad(state, readRoundEnemyProjection) {
  const board = state.preparation.units.filter(unit => unit.location.kind === 'board');
  return { players: board.filter(unit => unit.team === 'player').length, enemies: board.filter(unit => unit.team === 'enemy').length,
    playerItems: state.items.filter(item => item.location.kind === 'unit').length,
    enemyItems: readRoundEnemyProjection ? readRoundEnemyProjection(state.round).items.length : null };
}
