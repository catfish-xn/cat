/* M8 B10 performance evidence (M8_PLAN.md §7.6, "压力战斗tick耗时" and "桌面压力表现").
 *
 * Budgets are the plan's targets and are reported, never relaxed here:
 *   domain tick    p95 <= 5 ms,    p99 <= 10 ms (pure domain step, isolated Node child process)
 *   frame interval p95 <= 33.3 ms, p99 <= 50 ms (Chromium, 1440x1000, normal and reduced motion)
 * Recorded without a budget: events per battle, active status/task/shield peaks, save envelope bytes, JS heap.
 *
 * Parts (run serially, never concurrently, so the browser never competes with the domain child):
 *   domain  - child process `node --expose-gc <this> --child=domain`.
 *     (a) full runs: FULL_RUNS below, a fixed list of 30 (build, seed) pairs. The first 24 are exactly the
 *         `npm run test:headless` pairs (scripts/verify-m5-headless.cjs SEEDS, builds cannon/sniper/mage by
 *         index % 3); the last 6 use the M6 F1 "full-load" policy (9 players, three-slot equipment;
 *         scripts/verify-m6-full-load-helper.cjs) on seeds 42,2,3,5,8,11. Each route is first generated by
 *         its normal policy (scripts/generate-m5-route.cjs through Vite SSR, like test:headless; untimed),
 *         then its recorded public commands are replayed in a lean loop where process.hrtime.bigint()
 *         brackets api.stepMatch(state) only: no hashing, ledger oracle, history capture or logging is
 *         inside the timed region. The replay must reproduce the generated final-state hash. One full replay
 *         of the first route is a discarded warm-up; global.gc() runs between routes (outside timing), so GC
 *         inside a route is still charged to the ticks that trigger it. The tick that ends a combat (with
 *         settlement and loot) is included in the budget sample and also reported separately.
 *     (b) 9v9 engine pressure: tests/fixtures/m8/pressure-9v9.cjs, variants "distinct" and "mirror"; 18 units,
 *         three-star, three M8 completed items each. One discarded warm-up combat per variant (rng 0), then
 *         rng seeds 1..N (default 20) per variant; hrtime brackets stepCombat(state) only.
 *   browser - Vite dev server on port 0 (`--target=preview` serves the existing dist/ instead; run
 *         `npm run build` first). The densest pre-battle preparation of the full-load seed-42 route (most
 *         units on board, then most equipment, then most events) is exported as an ordinary save envelope
 *         with its completed battle records and loaded through the product's own import control; the combat
 *         is then started with a native click on the public start button and runs at the product's real
 *         50 ms tick (1x). requestAnimationFrame intervals are recorded in-page from the first combat frame
 *         through the first post-combat frame (or --browser-window-ms), once with prefers-reduced-motion
 *         'no-preference' and once with 'reduce'. No sample is dropped; intervals that end while the page is
 *         hidden are counted and reported separately (expected 0) and excluded from the budget statistic.
 *
 * Usage:
 *   node scripts/verify-m8-performance.cjs              # formal: all parts, 30 seeds, 20 reps, whole combat
 *   node scripts/verify-m8-performance.cjs --strict     # same, exit 1 when any budget fails
 *   node scripts/verify-m8-performance.cjs --part=domain --seeds=3 --pressure-reps=3        # smoke
 *   node scripts/verify-m8-performance.cjs --part=browser --browser-window-ms=5000          # smoke
 * Options: --part=domain|browser|all, --seeds=N (1..30, first N of FULL_RUNS), --pressure-reps=N,
 *   --browser-window-ms=N (0 = whole combat), --target=dev|preview.
 * Env: M8_PERFORMANCE_EVIDENCE_DIR (default artifacts/m8-performance), CHROMIUM_PATH (browser executable).
 * Default exit code is 0 even when budgets fail (report mode, manifest.blocking=false); `--strict` exits 1
 * on any budget failure; an exception in any part always exits 1.
 */
