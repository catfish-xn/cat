/** Nearest-rank percentiles over every sample; no sample is removed. */
function distribution(values) {
  const sorted = Float64Array.from(values).sort();
  const at = p => sorted.length ? sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil(sorted.length * p) - 1))] : null;
  let sum = 0; for (const value of sorted) sum += value;
  return { count: sorted.length, mean: sorted.length ? sum / sorted.length : null, p50: at(0.5), p95: at(0.95), p99: at(0.99), max: sorted.length ? sorted[sorted.length - 1] : null };
}
const countStats = values => { const d = distribution(values); return { ...d, min: values.length ? Math.min(...values) : null }; };
function judge(id, stats, threshold, extra = {}) {
  const checks = Object.fromEntries(Object.entries(threshold).map(([key, limit]) => [key, stats[key] !== null && stats[key] <= limit]));
  return { id, unit: 'ms', statistic: 'nearest-rank percentile over all samples', threshold, ...stats, checks,
    pass: stats.count > 0 && Object.values(checks).every(Boolean), ...extra };
}
/** 0.1 ms bins below 20 ms, 1 ms bins below 100 ms, one overflow bin: an audit trail without raw dumps. */
function histogram(values) {
  const bins = new Map();
  for (const value of values) {
    const key = value < 20 ? (Math.floor(value * 10) / 10).toFixed(1) : value < 100 ? String(Math.floor(value)) : '>=100';
    bins.set(key, (bins.get(key) ?? 0) + 1);
  }
  return Object.fromEntries([...bins].sort((a, b) => (a[0] === '>=100') - (b[0] === '>=100') || Number(a[0]) - Number(b[0])));
}
