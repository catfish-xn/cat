/**
 * Lean deterministic replay of recorded public commands. Only api.stepMatch(state) sits between the two
 * hrtime reads; the event filter, sample push, status count and records happen after the second read.
 */
function replayRoute(modules, entry, measure) {
  const { api } = modules, { dispatch } = ROUTES.normal, { hash } = require('./m4-evidence.cjs');
  const runId = `m8-performance-${entry.build}-${entry.seed}`;
  const combatTicks = [], terminalTicks = [], battles = [], records = [], worst = [];
  let state = api.createMatch(entry.seed);
  for (const command of entry.commands) {
    const context = state, outcome = dispatch(api, state, command);
    assert(outcome.ok !== false, `${runId}: replayed ${JSON.stringify(command)} -> ${outcome.reason}`);
    state = outcome.state;
    if (command.type !== 'start') continue;
    const initial = state.combat, events = outcome.events.filter(event => event.domain === 'combat');
    let peak = activeEntries(initial), ticks = 0;
    while (state.phase === 'combat') {
      const t0 = process.hrtime.bigint();
      const step = api.stepMatch(state);
      const ms = Number(process.hrtime.bigint() - t0) / 1e6;
      state = step.state; ticks++;
      for (const event of step.events) if (event.domain === 'combat') events.push(event);
      if (!measure) continue;
      const ended = state.phase !== 'combat';
      (ended ? terminalTicks : combatTicks).push(ms);
      if (worst.length < 10 || ms > worst[worst.length - 1].ms) {
        worst.push({ ms, round: context.roundDefinitionId, tick: state.combat?.tick ?? null, terminal: ended });
        worst.sort((a, b) => b.ms - a.ms); worst.length = Math.min(worst.length, 10);
      }
      peak = peakOf(peak, activeEntries(state.combat));
    }
    if (!measure) continue;
    records.push(battleRecord(modules, runId, context, initial, events, state.combat));
    battles.push({ round: context.roundDefinitionId, ticks, events: events.length, peak, load: boardLoad(context, modules.readRoundEnemyProjection) });
  }
  assert.equal(hash(state), entry.finalHash, `${runId}: lean replay reproduces the generated final state`);
  return { runId, final: state, combatTicks, terminalTicks, battles, records, worst };
}

// ---------------------------------------------------------------- domain child
async function domainChild() {
  const started = process.hrtime.bigint(), gc = () => global.gc?.();
  const result = { kind: 'domain', node: process.version, gcExposed: typeof global.gc === 'function', runs: FULL_RUNS.slice(0, OPTIONS.seeds),
    pressureReps: OPTIONS.pressureReps, timedRegion: 'process.hrtime.bigint() around api.stepMatch(state) / stepCombat(state) only' };
  const server = await ssrServer();
  try {
    const modules = await loadModules(server);
    // 1. Untimed generation by each route's normal policy; keep only the command list and final hash.
    const generated = [];
    for (const run of result.runs) {
      const t = process.hrtime.bigint(), route = await generateRoute(modules.api, run);
      generated.push({ ...run, commands: route.actions.map(action => action.command), finalHash: require('./m4-evidence.cjs').hash(route.final),
        outcome: route.final.outcome, finalRound: route.final.round, generationMs: Math.round(msSince(t)) });
      console.log(`[domain] generated ${run.build}-${run.seed}: ${route.actions.length} commands, ${route.summary.ticks} ticks, ${Math.round(msSince(t))} ms`);
      gc();
    }
    // 2. Warm-up replay of the first route, discarded.
    { const t = process.hrtime.bigint(); replayRoute(modules, generated[0], false); result.warmUp = { route: `${generated[0].build}-${generated[0].seed}`, ms: Math.round(msSince(t)) }; gc(); }
    // 3. Measured replays.
    const allTicks = [], allTerminal = [], perBattleEvents = [], perRoute = [];
    let worst = [], peak = {}, heapPeak = 0, rssPeak = 0;
    for (const entry of generated) {
      const t = process.hrtime.bigint(), replay = replayRoute(modules, entry, true), wallMs = msSince(t);
      for (const ms of replay.combatTicks) allTicks.push(ms);
      for (const ms of replay.terminalTicks) allTicks.push(ms), allTerminal.push(ms);
      for (const battle of replay.battles) { perBattleEvents.push(battle.events); peak = peakOf(peak, battle.peak); }
      worst = [...worst, ...replay.worst.map(w => ({ route: replay.runId, ...w }))].sort((a, b) => b.ms - a.ms).slice(0, 20);
      const envelope = envelopeOf(replay.runId, replay.final, replay.records);
      const saveBytes = Buffer.byteLength(JSON.stringify(envelope)), recordBytes = replay.records.map(r => Buffer.byteLength(JSON.stringify(r)));
      const memory = process.memoryUsage(); heapPeak = Math.max(heapPeak, memory.heapUsed); rssPeak = Math.max(rssPeak, memory.rss);
      const routeTicks = [...replay.combatTicks, ...replay.terminalTicks];
      perRoute.push({ route: replay.runId, build: entry.build, seed: entry.seed, outcome: entry.outcome, finalRound: entry.finalRound, battles: replay.battles.length,
        ticks: routeTicks.length, tickMs: distribution(routeTicks), replayWallMs: Math.round(wallMs), generationMs: entry.generationMs,
        eventsPerBattle: countStats(replay.battles.map(b => b.events)), maxLoad: replay.battles.reduce((m, b) => (b.load.players + b.load.enemies) * 100 + b.load.playerItems > (m ? (m.players + m.enemies) * 100 + m.playerItems : -1) ? b.load : m, null),
        saveEnvelopeBytes: saveBytes, largestBattleRecordBytes: Math.max(0, ...recordBytes), heapUsedBytesAfter: memory.heapUsed, battlesDetail: replay.battles });
      console.log(`[domain] replayed ${replay.runId}: ${routeTicks.length} ticks p95 ${distribution(routeTicks).p95.toFixed(3)} ms, save ${saveBytes} B`);
      gc();
    }
    result.fullRuns = { tickMs: distribution(allTicks), terminalTickMs: distribution(allTerminal), histogram: histogram(allTicks), worstTicks: worst,
      eventsPerBattle: countStats(perBattleEvents), activePeak: peak, saveEnvelopeBytes: countStats(perRoute.map(r => r.saveEnvelopeBytes)),
      largestBattleRecordBytes: Math.max(0, ...perRoute.map(r => r.largestBattleRecordBytes)), heapUsedPeakBytes: heapPeak, rssPeakBytes: rssPeak, routes: perRoute };

    // 4. 9v9 engine pressure fixture.
    const pressureFixture = require('../tests/fixtures/m8/pressure-9v9.cjs');
    const fixtureModules = await pressureFixture.loadModules(server);
    const { createHash } = require('node:crypto');
    result.pressureSpecSha256 = createHash('sha256').update(JSON.stringify(pressureFixture.SPEC)).digest('hex');
    const pressureCombat = (variant, seed, measure) => {
      const built = pressureFixture.build(fixtureModules, seed, variant), ticks = [];
      let state = built.step.state, events = built.step.events.length, peakEntries = activeEntries(state);
      while (state.status !== 'finished') {
        const t0 = process.hrtime.bigint();
        const step = fixtureModules.combat.stepCombat(state);
        const ms = Number(process.hrtime.bigint() - t0) / 1e6;
        state = step.state; events += step.events.length;
        if (measure) { ticks.push(ms); peakEntries = peakOf(peakEntries, activeEntries(state)); }
      }
      return { summary: built.summary, ticks, events, peak: peakEntries, result: state.result, endTick: state.tick };
    };
    result.pressure = {};
    for (const variant of PRESSURE_VARIANTS) {
      pressureCombat(variant, 0, false); gc();
      const ticks = [], combats = [];
      let fixture = null;
      for (let seed = 1; seed <= OPTIONS.pressureReps; seed++) {
        const run = pressureCombat(variant, seed, true);
        fixture ??= run.summary;
        for (const ms of run.ticks) ticks.push(ms);
        combats.push({ rngSeed: seed, ticks: run.ticks.length, events: run.events, result: run.result, peak: run.peak, tickMs: distribution(run.ticks) });
      }
      const memory = process.memoryUsage();
      result.pressure[variant] = { fixture, rngSeeds: [1, OPTIONS.pressureReps],
        tickMs: distribution(ticks), histogram: histogram(ticks), eventsPerCombat: countStats(combats.map(c => c.events)),
        ticksPerCombat: countStats(combats.map(c => c.ticks)), activePeak: combats.reduce((p, c) => peakOf(p, c.peak), {}), heapUsedBytesAfter: memory.heapUsed, combats };
      console.log(`[domain] pressure ${variant}: ${ticks.length} ticks p95 ${distribution(ticks).p95.toFixed(3)} ms p99 ${distribution(ticks).p99.toFixed(3)} ms`);
      gc();
    }
  } finally { await server.close(); }
  result.durationMs = Math.round(msSince(started));
  return result;
}

function runDomainChild() {
  fs.mkdirSync(OUTPUT, { recursive: true });
  const out = path.join(OUTPUT, 'domain.json');
  fs.rmSync(out, { force: true });
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['--expose-gc', __filename, '--child=domain', `--seeds=${OPTIONS.seeds}`, `--pressure-reps=${OPTIONS.pressureReps}`],
      { cwd: ROOT, stdio: 'inherit', env: { ...process.env, M8_PERFORMANCE_EVIDENCE_DIR: OUTPUT } });
    child.on('error', reject);
    child.on('exit', code => {
      if (code !== 0) return reject(new Error(`domain child exited with ${code}`));
      try { resolve(JSON.parse(fs.readFileSync(out, 'utf8'))); } catch (error) { reject(error); }
    });
  });
}

// ---------------------------------------------------------------- browser part
/** Builds the import envelope for the densest legal pre-battle preparation of BROWSER_ROUTE (untimed). */
async function browserEnvelope(modules) {
  const runId = `m8-performance-browser-${BROWSER_ROUTE.build}-${BROWSER_ROUTE.seed}`;
  const records = [], candidates = [];
  let current = null;
  const route = await generateRoute(modules.api, BROWSER_ROUTE, (before, result, command) => {
    if (command?.type === 'start') {
      candidates.push({ before, battles: [...records], load: boardLoad(before, modules.readRoundEnemyProjection), events: 0 });
      current = { context: before, initial: result.state.combat, events: result.events.filter(event => event.domain === 'combat') };
    } else if (!command && current) {
      for (const event of result.events) if (event.domain === 'combat') current.events.push(event);
    }
    if (current && result.state.combat?.status === 'finished' && result.state.phase !== 'combat') {
      records.push(battleRecord(modules, runId, current.context, current.initial, current.events, result.state.combat));
      candidates.at(-1).events = current.events.length; current = null;
    }
  });
  assert.equal(route.final.phase, 'gameOver');
  const score = c => [c.load.players + c.load.enemies, c.load.playerItems + (c.load.enemyItems ?? 0), c.events];
  const chosen = candidates.reduce((best, c) => {
    const a = score(c), b = best ? score(best) : null;
    return !b || a[0] > b[0] || a[0] === b[0] && (a[1] > b[1] || a[1] === b[1] && a[2] >= b[2]) ? c : best;
  }, null);
  return { envelope: envelopeOf(runId, chosen.before, chosen.battles),
    segment: { route: `${BROWSER_ROUTE.build}-${BROWSER_ROUTE.seed}`, round: chosen.before.roundDefinitionId, roundOrdinal: chosen.before.round,
      load: chosen.load, expectedCombatEvents: chosen.events, completedBattleRecords: chosen.battles.length } };
}

const FRAME_SAMPLER = () => {
  const perf = window.__M8_PERF__ = { armed: false, sawCombat: false, done: false, windowMs: 0, firstCombatAt: null, lastCombatAt: null,
    samples: [], hidden: 0, combatFrames: 0, clickAt: null };
  let previous;
  const inCombat = () => document.querySelector('[data-debug="mobile:start-combat"]')?.textContent === '战斗进行中…';
  function frame(now) {
    if (perf.armed && !perf.done) {
      const combat = inCombat();
      if (combat && !perf.sawCombat) { perf.sawCombat = true; perf.firstCombatAt = now; }
      if (perf.sawCombat && previous !== undefined) {
        // An interval belongs to the combat segment when it ends on a combat frame, plus the one interval
        // ending on the first post-combat frame (settlement rendering). Hidden intervals are only counted.
        if (document.visibilityState === 'visible') perf.samples.push(now - previous); else perf.hidden++;
      }
      if (combat) { perf.combatFrames++; perf.lastCombatAt = now; }
      if (perf.sawCombat && (!combat || (perf.windowMs > 0 && now - perf.firstCombatAt >= perf.windowMs))) { perf.done = true; perf.endedInCombat = combat; }
    }
    previous = now;
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
};

