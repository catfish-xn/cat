#!/usr/bin/env python3
"""Emit reviewed G2 runtime data from the hash-gated normalized inventory; --check is read-only."""
import argparse
import runpy
import sys
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src/simulation/content/source/s13-14.24b/normalized'
EXISTING = set('irelia maddie darius lux zyra tristana urgot rell leona vander kogmaw scar ezreal loris nami corki garen zoe caitlyn'.split())

def outputs():
    rows = json.loads((DATA / 'g2-1-champions.json').read_text())['champions']
    new = [c for c in rows if c['id'] not in EXISTING and c['status'] != 'blocked-on-form-stats']
    units, abilities = {}, {}
    for c in new:
        n, s = c['id'], c['stats']
        if any(v is None for v in s.values()):
            raise ValueError('Missing source stat: ' + n)
        units[n] = dict(id=n, name=c['name'], symbol=c['name'][0], color=10466749, cost=c['cost'],
                        baseStats={k:int(s[k]) for k in ('health','attack','armor','magicResist')},
                        attackRange=int(s['attackRange']), attackIntervalTicks=s['attackIntervalTicks'],
                        baseAttackSpeedBps=s['attackSpeedBps'], initialMana=int(s['initialMana']),
                        maxMana=int(s['maxMana']), abilityId=n+'-ability', traits=c['runtimeTraits'])
        abilities[n+'-ability'] = c['ability']
    existing_traits = {c['id']: c['runtimeTraits'] for c in rows if c['id'] in EXISTING and set(c['sourceTraits']) & {'Automata','Firelight','Family'}}
    def ts(value):
        return json.dumps(value, ensure_ascii=False, indent=2) + ';\n'
    return {'src/simulation/content/g2-units.ts': "// Generated by scripts/generate-g2-content.py; source pointers are in normalized/g2-1-champions.json.\nimport type { UnitDefinition } from '../unit-types';\nimport { freezeContent } from './freeze';\nexport const G2_UNIT_DEFINITIONS: Readonly<Record<string, UnitDefinition>> = freezeContent(" + ts(units).replace(';\n', ');\n') + 'export const G2_EXISTING_TRAITS: Readonly<Record<string, readonly string[]>> = freezeContent(' + ts(existing_traits).replace(';\n', ');\n'),
            'src/simulation/content/g2-abilities.ts': "// Generated by scripts/generate-g2-content.py; coefficients round source floats to four decimal places.\nimport type { S13AbilityData } from './abilities';\nimport { freezeContent } from './freeze';\nexport const G2_ABILITY_DATA: Readonly<Record<string, Omit<S13AbilityData, \'name\'>>> = freezeContent(" + ts(abilities).replace(';\n', ');\n')}

if __name__ == '__main__':
    if '--g2-2' in sys.argv:
        sys.argv.remove('--g2-2')
        runpy.run_path(str(ROOT / 'scripts/generate-g2-2-content.py'), run_name='__main__')
        sys.exit(0)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for rel, content in outputs().items():
        p = ROOT / rel
        if args.check:
            if p.read_text() != content:
                raise ValueError('Generated runtime differs: ' + rel)
        else:
            p.write_text(content)
