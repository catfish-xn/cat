/*
 * Downloads the official S13 (patch 14.24) champion, trait and item icons referenced by the
 * archived client data into public/assets/s13, and writes the asset manifest used at runtime.
 * Source: CommunityDragon mirror of the 14.24 game files. Riot Games assets are used under
 * Riot's "Legal Jibber Jabber" policy for free, non-commercial fan projects; see README.
 *
 * Usage: node scripts/fetch-s13-assets.cjs        (needs network access to raw.communitydragon.org)
 * Runtime never fetches remotely: only files listed in the generated manifest are referenced.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const ARCHIVE = require('../src/simulation/content/source/s13-14.24.json');
const PATCH = '14.24';
const OUT = path.join(ROOT, 'public/assets/s13');
const MANIFEST = path.join(ROOT, 'src/presentation/s13-asset-manifest.ts');
const toUrl = asset => `https://raw.communitydragon.org/${PATCH}/game/${asset.toLowerCase().replace(/\.(tex|dds)$/, '.png')}`;

const ITEM_IDS = { TFT_Item_BFSword: 'sword', TFT_Item_RecurveBow: 'bow', TFT_Item_NeedlesslyLargeRod: 'rod', TFT_Item_TearOfTheGoddess: 'tear',
  TFT_Item_ChainVest: 'vest', TFT_Item_NegatronCloak: 'cloak', TFT_Item_GiantsBelt: 'belt', TFT_Item_GuinsoosRageblade: 'rageblade',
  TFT_Item_Deathblade: 'deathblade', TFT_Item_SpearOfShojin: 'shojin', TFT_Item_ArchangelsStaff: 'archangel', TFT_Item_RabadonsDeathcap: 'deathcap',
  TFT_Item_WarmogsArmor: 'warmog', TFT_Item_DragonsClaw: 'dragons-claw', TFT_Item_GargoyleStoneplate: 'gargoyle', TFT_Item_HextechGunblade: 'gunblade' };

function jobs() {
  const list = [];
  for (const [id, champion] of Object.entries(ARCHIVE.champions)) list.push({ kind: 'champion', id, asset: champion.tileIcon });
  for (const trait of ARCHIVE.traits) list.push({ kind: 'trait', id: trait.apiName, asset: trait.icon });
  const items = Array.isArray(ARCHIVE.items) ? ARCHIVE.items : Object.values(ARCHIVE.items);
  for (const item of items) if (item.icon) list.push({ kind: 'item', id: ITEM_IDS[item.apiName] ?? item.apiName, apiName: item.apiName, asset: item.icon });
  return list;
}

const results = [];
for (const job of jobs()) {
  const url = toUrl(job.asset), file = path.join(OUT, `${job.kind}s`, `${job.id}.png`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  try {
    // curl honours the environment's HTTPS proxy; Node fetch does not.
    execFileSync('curl', ['-sSfL', '--max-time', '30', '-o', file, url], { stdio: ['ignore', 'ignore', 'pipe'] });
    const bytes = fs.readFileSync(file);
    if (bytes.subarray(0, 4).toString('hex') !== '89504e47') throw new Error('not a PNG');
    results.push({ kind: job.kind, id: job.id, path: `assets/s13/${job.kind}s/${job.id}.png`, source: url, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex') });
    console.log(`ok   ${job.kind} ${job.id} ${bytes.length}B`);
  } catch (error) {
    fs.rmSync(file, { force: true });
    console.log(`FAIL ${job.kind} ${job.id} ${url} ${String(error.message).split('\n')[0]}`);
  }
}
const body = `/* Generated by scripts/fetch-s13-assets.cjs — do not edit. Riot Games assets, see README. */\n`
  + `export interface S13Asset { readonly kind: 'champion' | 'trait' | 'item'; readonly id: string; readonly path: string; readonly source: string; readonly bytes: number; readonly sha256: string }\n`
  + `export const S13_ASSET_PATCH = '${PATCH}';\n`
  + `export const S13_ASSETS: readonly S13Asset[] = ${JSON.stringify(results, null, 2)};\n`;
fs.writeFileSync(MANIFEST, body);
console.log(`${results.length}/${jobs().length} assets written; manifest ${path.relative(ROOT, MANIFEST)}`);
if (results.length !== jobs().length) process.exitCode = 1;
