/*
 * Downloads the official S13 (patch 14.24) champion, trait and item icons referenced by the
 * archived client data into public/assets/s13, and writes the asset manifest used at runtime.
 * Source: CommunityDragon mirror of the 14.24 game files. Riot Games assets are used under
 * Riot's "Legal Jibber Jabber" policy for free, non-commercial fan projects; see README.
 *
 * Usage: node scripts/fetch-s13-assets.cjs        (needs network access to raw.communitydragon.org)
 * Runtime never fetches remotely: only files listed in the generated manifest are referenced.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const ARCHIVE = require('../src/simulation/content/source/s13-14.24.json');
const PATCH = '14.24';
const G2 = process.argv.includes('--g2-1');
const OUT = path.join(ROOT, 'public/assets/s13');
const MANIFEST = path.join(ROOT, 'src/presentation/s13-asset-manifest.ts');
const toUrl = asset => `https://raw.communitydragon.org/${PATCH}/game/${asset.toLowerCase().replace(/\.(tex|dds)$/, '.png')}`;

const ITEM_IDS = { TFT_Item_BFSword: 'sword', TFT_Item_RecurveBow: 'bow', TFT_Item_NeedlesslyLargeRod: 'rod', TFT_Item_TearOfTheGoddess: 'tear',
  TFT_Item_ChainVest: 'vest', TFT_Item_NegatronCloak: 'cloak', TFT_Item_GiantsBelt: 'belt', TFT_Item_GuinsoosRageblade: 'rageblade',
  TFT_Item_Deathblade: 'deathblade', TFT_Item_SpearOfShojin: 'shojin', TFT_Item_ArchangelsStaff: 'archangel', TFT_Item_RabadonsDeathcap: 'deathcap',
  TFT_Item_WarmogsArmor: 'warmog', TFT_Item_DragonsClaw: 'dragons-claw', TFT_Item_GargoyleStoneplate: 'gargoyle', TFT_Item_HextechGunblade: 'gunblade' };

function jobs() {
  const list = [];
  if (G2) {
    const normalized = path.join(ROOT, 'src/simulation/content/source/s13-14.24b/normalized');
    for (const c of JSON.parse(fs.readFileSync(path.join(normalized, 'g2-1-champions.json'))).champions)
      list.push({kind:'champion',id:c.id,asset:c.record.tileIcon,apiName:c.apiName});
    for (const t of JSON.parse(fs.readFileSync(path.join(normalized, 'g2-1-traits.json'))).traits)
      list.push({kind:'trait',id:t.record.name.toLowerCase(),asset:t.record.icon,apiName:t.record.apiName});
    const bundled = require('esbuild').buildSync({stdin:{contents:"export { ITEM_DEFINITIONS } from './src/simulation/content/items';",resolveDir:ROOT,loader:'ts'},bundle:true,platform:'node',format:'cjs',write:false});
    const mod = new (require('node:module').Module)('g2-assets', module);
    mod._compile(bundled.outputFiles[0].text, path.join(ROOT,'g2-assets.cjs'));
    const runtimeItems = mod.exports.ITEM_DEFINITIONS;
    for (const item of Object.values(runtimeItems)) {
      const row=JSON.parse(fs.readFileSync(path.join(normalized,'g2-1-items.json'))).items.find(r=>r.record.apiName===item.apiName);
      if(!row)throw new Error(`No normalized item source: ${item.id}`);
      list.push({kind:'item',id:item.id,apiName:item.apiName,asset:row.record.icon});
    }
    return list;
  }
  for (const [id, champion] of Object.entries(ARCHIVE.champions)) list.push({ kind: 'champion', id, asset: champion.tileIcon });
  for (const trait of ARCHIVE.traits) list.push({ kind: 'trait', id: trait.apiName, asset: trait.icon });
  const items = Array.isArray(ARCHIVE.items) ? ARCHIVE.items : Object.values(ARCHIVE.items);
  for (const item of items) if (item.icon) list.push({ kind: 'item', id: ITEM_IDS[item.apiName] ?? item.apiName, apiName: item.apiName, asset: item.icon });
  return list;
}

const results = [];
for (const job of jobs()) {
  const url = toUrl(job.asset), file = path.join(OUT, `${job.kind}s`, `${job.id}.png`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  try {
    // curl honours the environment's HTTPS proxy; Node fetch does not.
    execFileSync('curl', ['-sSfL', '--max-time', '30', '-o', file, url], { stdio: ['ignore', 'ignore', 'pipe'] });
    const bytes = fs.readFileSync(file);
    if (bytes.subarray(0, 4).toString('hex') !== '89504e47') throw new Error('not a PNG');
    results.push({ ...(job.apiName ? {apiName:job.apiName}:{}), kind: job.kind, id: job.id, path: `assets/s13/${job.kind}s/${job.id}.png`, source: url, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex') });
    console.log(`ok   ${job.kind} ${job.id} ${bytes.length}B`);
  } catch (error) {
    fs.rmSync(file, { force: true });
    console.log(`FAIL ${job.kind} ${job.id} ${url} ${String(error.message).split('\n')[0]}`);
  }
}
const existing = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8').split('S13_ASSETS: readonly S13Asset[] = ')[1].trim().replace(/;$/, '')) : [];
const merged = new Map(existing.map(asset => [asset.kind + ":" + asset.id, asset]));
for (const asset of results) merged.set(asset.kind + ":" + asset.id, asset);
const body = `/* Generated by scripts/fetch-s13-assets.cjs — do not edit. Riot Games assets, see README. */\n`
  + `export interface S13Asset { readonly apiName?: string; readonly kind: 'champion' | 'trait' | 'item'; readonly id: string; readonly path: string; readonly source: string; readonly bytes: number; readonly sha256: string }\n`
  + `export const S13_ASSET_PATCH = '${PATCH}';\n`
  + `export const S13_ASSETS: readonly S13Asset[] = ${JSON.stringify([...merged.values()], null, 2)};\n`;
if (G2) {
  const target=path.join(ROOT,'docs/evidence/g2-1/assets-manifest.json');
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,JSON.stringify({patch:PATCH,upstreamSha256:'c1237ba2441f932a1b9761ce12887ad21089dffbd3a8004671cc9cb82dfd5bd3',command:'node scripts/fetch-s13-assets.cjs --g2-1',downloadDirectory:'public/assets/s13',publicAssetsCommitted:true,expected:jobs().length,downloaded:results.length,assets:results},null,2)+'\n');
}
if (results.length === jobs().length) fs.writeFileSync(MANIFEST, body);
console.log(`${results.length}/${jobs().length} assets written; manifest ${G2 ? 'docs/evidence/g2-1/assets-manifest.json' : path.relative(ROOT, MANIFEST)}`);
if (results.length !== jobs().length) process.exitCode = 1;
