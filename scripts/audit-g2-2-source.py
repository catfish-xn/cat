#!/usr/bin/env python3
"""Hash-gated G2-2 admission evidence. No runtime or identity mutations."""
import argparse
import importlib.util
import json
import sys
sys.dont_write_bytecode = True
from pathlib import Path
spec = importlib.util.spec_from_file_location('source', Path(__file__).with_name('import-m8-source.py'))
source = importlib.util.module_from_spec(spec)
spec.loader.exec_module(source)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
def write(path, text):
    if args.check:
        if path.read_text() != text:
            raise ValueError('Generated evidence differs: ' + str(path))
    else:
        path.write_text(text)

data = source.load_source(source.DEST / 'raw/en_us.json.gz')
i, _ = source.select(data)
mode = data['setData'][i]
out = source.ROOT / 'docs/evidence/g2-2'
out.mkdir(parents=True, exist_ok=True)
records = [(j, c) for j, c in enumerate(mode['champions']) if 'Swain' in c['apiName']]
def leaves(value, path=''):
    if isinstance(value, dict):
        for key, child in value.items():
            yield from leaves(child, path + '/' + key)
    elif isinstance(value, list) and value:
        for index, child in enumerate(value):
            yield from leaves(child, path + '/' + str(index))
    else:
        yield path, value
text = '# Swain 形态准入证据\n\n来源：`src/simulation/content/source/s13-14.24b/raw/en_us.json.gz`。\n\n解压后 SHA256：`' + source.SHA256 + '`。仅使用 `mutator=TFTSet13` 标准模式。\n\n结论：暂不准入。源本体的 `magicResist` 为 null；恶魔形态的 `hp`、`damage`、`armor` 为 null。源中的 0 保留为 0，null 标为“缺”；不跨形态借值。恶魔形态技能为占位文案，不能据此实现远程/近战切换。\n'
for j, c in records:
    pointer = f'/setData/{i}/champions/{j}'
    text += f'\n## {c["apiName"]}\n\nJSON pointer: `{pointer}`；记录 canonical SHA256: `{source.digest(c)}`。\n\n| 字段（相对 pointer） | 源值 |\n|---|---|\n'
    for key, value in leaves(c):
        rendered = '缺' if value is None else json.dumps(value, ensure_ascii=False)
        text += f'| `{key}` | {rendered.replace("|", "&#124;")} |\n'
text += '\n## 源中未提供的形态合同\n\n| 字段 | 证据 |\n|---|---|\n| 远程形态完整属性 | 缺 |\n| 远程形态技能/系数 | 缺 |\n| 站位与形态选择条件 | 缺 |\n| 本体到恶魔形态属性覆盖规则 | 缺 |\n| 切换时法力继承规则 | 缺 |\n'
write(out / 'SWAIN.md', text)

# Display source is separate from combat coefficients: no inactive trait is enabled.
old = json.loads((source.DEST / 'normalized/g2-1-champions.json').read_text())['champions']
if old != source.g2_outputs(data)['normalized/g2-1-champions.json']['champions']:
    raise ValueError('G2-1 normalized inventory differs from locked source')
admitted = source.g22_outputs(data)['normalized/g2-2-champions.json']['champions']
names = {c['id']: {'name': c['record']['ability']['name'],
    'variables': {v['name']: [round(n,4) for n in v['value'][1:4]]
        for v in c['record']['ability']['variables'] if v['value'] is not None}}
    for c in admitted}
write(source.ROOT / 'src/simulation/ability-display-source.ts',
    '// Generated by scripts/audit-g2-2-source.py from hash-locked CDragon.\n'
    + "import { freezeContent } from './content/freeze';\n" + 'export const ABILITY_DISPLAY_SOURCE = freezeContent(' + json.dumps(names, ensure_ascii=False, indent=2) + ' as const);\n')
