#!/usr/bin/env python3
"""Hash-gated G2-2 admission evidence. No runtime or identity mutations."""
import argparse
import importlib.util
import json
import sys
sys.dont_write_bytecode = True
from pathlib import Path
spec = importlib.util.spec_from_file_location('source', Path(__file__).with_name('import-m8-source.py'))
source = importlib.util.module_from_spec(spec)
spec.loader.exec_module(source)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
def write(path, text):
    if args.check:
        if path.read_text() != text:
            raise ValueError('Generated evidence differs: ' + str(path))
    else:
        path.write_text(text)

data = source.load_source(source.DEST / 'raw/en_us.json.gz')
i, _ = source.select(data)
mode = data['setData'][i]
out = source.ROOT / 'docs/evidence/g2-2'
out.mkdir(parents=True, exist_ok=True)
records = [(j, c) for j, c in enumerate(mode['champions']) if 'Swain' in c['apiName']]
def leaves(value, path=''):
    if isinstance(value, dict):
        for key, child in value.items():
            yield from leaves(child, path + '/' + key)
    elif isinstance(value, list) and value:
        for index, child in enumerate(value):
            yield from leaves(child, path + '/' + str(index))
    else:
        yield path, value
text = '# Swain 形态准入证据\n\n来源：`src/simulation/content/source/s13-14.24b/raw/en_us.json.gz`。\n\n解压后 SHA256：`' + source.SHA256 + '`。仅使用 `mutator=TFTSet13` 标准模式。\n\n结论：暂不准入。源本体的 `magicResist` 为 null；恶魔形态的 `hp`、`damage`、`armor` 为 null。源中的 0 保留为 0，null 标为“缺”；不跨形态借值。恶魔形态技能为占位文案，不能据此实现远程/近战切换。\n'
for j, c in records:
    pointer = f'/setData/{i}/champions/{j}'
    text += f'\n## {c["apiName"]}\n\nJSON pointer: `{pointer}`；记录 canonical SHA256: `{source.digest(c)}`。\n\n| 字段（相对 pointer） | 源值 |\n|---|---|\n'
    for key, value in leaves(c):
        rendered = '缺' if value is None else json.dumps(value, ensure_ascii=False)
        text += f'| `{key}` | {rendered.replace("|", "&#124;")} |\n'
text += '\n## 源中未提供的形态合同\n\n| 字段 | 证据 |\n|---|---|\n| 远程形态完整属性 | 缺 |\n| 远程形态技能/系数 | 缺 |\n| 站位与形态选择条件 | 缺 |\n| 本体到恶魔形态属性覆盖规则 | 缺 |\n| 切换时法力继承规则 | 缺 |\n'
write(out / 'SWAIN.md', text)

# Display source is separate from combat coefficients: no inactive trait is enabled.
old = json.loads((source.DEST / 'normalized/g2-1-champions.json').read_text())['champions']
if old != source.g2_outputs(data)['normalized/g2-1-champions.json']['champions']:
    raise ValueError('G2-1 normalized inventory differs from locked source')
names = {c['id']: {'name': c['record']['ability']['name'],
    'variables': {v['name']: [round(n, 4) for n in v['value'][1:4]]
                  for v in c['record']['ability']['variables'] if v['value'] is not None}}
         for c in old if c['status'] != 'blocked-on-form-stats'}
write(source.ROOT / 'src/simulation/ability-display-source.ts',
    '// Generated by scripts/audit-g2-2-source.py from hash-locked CDragon.\n'
    + "import { freezeContent } from './content/freeze';\n" + 'export const ABILITY_DISPLAY_SOURCE = freezeContent(' + json.dumps(names, ensure_ascii=False, indent=2) + ' as const);\n')

# Candidate inventory only. Admission remains separate from extraction.
factions = {'Rebel', 'Academy', 'Enforcer', 'Conqueror', 'Scrap', 'Emissary'}
old_api = {c['apiName'] for c in old}
candidates = []
for j, c in enumerate(mode['champions']):
    if c['apiName'] in old_api or c['cost'] not in range(1, 6) or not set(c['traits']) & factions:
        continue
    candidates.append({'sourcePointer': f'/setData/{i}/champions/{j}',
                       'canonicalSha256': source.digest(c), 'record': c,
                       'missingStats': [k for k, value in c['stats'].items() if value is None]})
trait_records = [{'sourcePointer': f'/setData/{i}/traits/{j}', 'record': t,
                  'canonicalSha256': source.digest(t)}
                 for j, t in enumerate(mode['traits']) if t['name'] in factions]
write(out / 'source-candidates.json', json.dumps({'sourceSha256': source.SHA256,
    'champions': candidates, 'traits': trait_records}, ensure_ascii=False, indent=2) + '\n')

md = '# G2-2 source reconciliation — admission pending\n\n'
md += '本文件记录候选证据，不代表已经发布 48 英雄 / 14 羁绊。当前运行时仍为 33 英雄 / 8 羁绊；CONTENT digest 未变更。\n\n'
md += '锁定源解压 SHA256：`' + source.SHA256 + '`。完整原始候选记录、逐星技能值和 canonical SHA256 见 `source-candidates.json`；每个变量的 1–3 星值取 `ability.variables[].value[1:4]`。\n\n'
md += '## 新增英雄候选\n\n| 英雄 | CDragon pointer | 费用 | HP / AD / 护甲 / 魔抗 | AS / 射程 / 初始法力 / 总法力 | 技能名 | 准入状态 |\n|---|---|---:|---|---|---|---|\n'
for c in candidates:
    r, p = c['record'], c['sourcePointer']
    s = r['stats']
    show = lambda k: '缺' if s[k] is None else str(s[k])
    md += f'| {r["name"]} (`{r["apiName"]}`) | `{p}` | {r["cost"]} | ' + ' / '.join(show(k) for k in ('hp','damage','armor','magicResist')) + ' | ' + ' / '.join(show(k) for k in ('attackSpeed','range','initialMana','mana')) + f' | {r["ability"]["name"]} | ' + ('缺形态属性，暂缓' if c['missingStats'] else '源属性完整；尚未实现运行时') + ' |\n'
md += '\n斯维因完整字段与缺失表见 `SWAIN.md`。上述候选有 14 名属性完整、2 名缺形态属性；补齐第 15 名的选择尚待确认。\n\n## 逐英雄技能值\n'
for c in candidates:
    r = c['record']
    md += f'\n### {r["name"]}\n\n| CDragon 字段（相对英雄 pointer） | 1 星 / 2 星 / 3 星 |\n|---|---|\n'
    for n, v in enumerate(r['ability']['variables']):
        values = '缺' if v['value'] is None else ' / '.join(str(round(x,4)) for x in v['value'][1:4])
        md += f'| `ability/variables/{n}` ({v["name"]}) | {values} |\n'
md += '\n## 六个阵营\n\n| 阵营 | CDragon pointer | 已有成员 | 新增候选 |\n|---|---|---|---|\n'
for t in trait_records:
    name = t['record']['name']
    existing = ', '.join(c['id'] for c in old if name in c['sourceTraits'] and c['status'] != 'blocked-on-form-stats')
    additions = ', '.join(c['record']['name'] for c in candidates if name in c['record']['traits'])
    md += f'| {name} | `{t["sourcePointer"]}` | {existing} | {additions} |\n'
for t in trait_records:
    r = t['record']
    md += f'\n### {r["name"]} 逐档数值\n\n| CDragon 字段（相对羁绊 pointer） | 源值 |\n|---|---|\n'
    for key, value in leaves(r['effects'], '/effects'):
        md += f'| `{key}` | ' + ('缺' if value is None else json.dumps(value)) + ' |\n'
md += '''
## 近似项与尚未具备的规则证据

- 数值展示将源浮点系数四舍五入到四位小数，与既有技能内容量化一致；AD/AP 换算随后使用整数基点与最终向下取整。
- `abilityDisplayValues` 仅展示基础属性/显式 AD/AP；未模拟目标抗性、暴击、队友数量或已累计的小炮成长。范德按每名队友增量展示，小炮累计成长为 0。
- 实验体字段取源值供解析；实验体尚未启用，不能把显示值作为运行时生效证据。
- Swain / Jayce / Gangplank 形态属性缺失，不以其他形态或其他英雄的属性替代。
- Conqueror 的羁绊记录包含 ADAPBase、StacksPerKill、PercentIncreasePerChest，但不包含宝箱阈值、掉落表及奖励抽取规则。是否允许仅战斗加成的有限实现需明确决定；本分支尚未启用。
- Academy 的羁绊记录有赞助装备个数和属性加成，没有赞助装备抽样池和发放时点。不能把整个普通装备池默认当成官方赞助池。
- Scrap 高档包含光明装备，按任务范围排除；不能为凑齐断点加入光明装备或转职。
- 本文件未声明任何新英雄或新阵营已经通过战斗验收。

## 可复现

`python3 scripts/audit-g2-2-source.py`：先校验原始字节长度和解压 SHA256，再生成源候选、Swain 全字段和展示源。
`npm test -- tests/g2-2-ability-display.test.ts`：SR-G2-01 原有 19 英雄 × 3 星占位符覆盖及独立公式样例。
'''
write(out / 'RECONCILIATION.md', md)

assets = []
for kind, identity, record in (
    [('champion', {'TFT13_Fish': 'steb'}.get(c['record']['apiName'], c['record']['apiName'].removeprefix('TFT13_').lower()), c['record']) for c in candidates]
    + [('trait', t['record']['name'].lower(), t['record']) for t in trait_records]
    + [('champion', 'swain', c) for _, c in records if c['apiName'] == 'TFT13_Swain']
):
    asset = record['tileIcon'] if kind == 'champion' else record['icon']
    path = source.ROOT / f'public/assets/s13/{kind}s/{identity}.png'
    url = 'https://raw.communitydragon.org/14.24/game/' + asset.lower().removesuffix('.tex') + '.png'
    assets.append({'id': identity, 'kind': kind, 'source': url,
        'path': str(path.relative_to(source.ROOT)),
        'sha256': source.hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None,
        'status': 'existing' if path.exists() else 'not-downloaded'})
write(out / 'assets-manifest.json', json.dumps({'status': 'candidate inventory; no new icons committed',
    'sourceSha256': source.SHA256, 'assets': assets}, ensure_ascii=False, indent=2) + '\n')
