#!/usr/bin/env python3
"""Generate G2-2 additions, membership and source names; never infer missing stats."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'src/simulation/content/source/s13-14.24b/normalized'
def outputs():
    rows=json.loads((DATA/'g2-2-champions.json').read_text())['champions']
    units,abilities,names,traits={},{},{},{}
    for c in rows:
        r=c['record']; n=c['id']; s=r['stats']; names[n+'-ability']=r['ability']['name']; traits[n]=c['runtimeTraits']
        if not c['new']:continue
        speed=round(s['attackSpeed']*10000)
        units[n]=dict(id=n,name=r['name'],symbol=r['name'][0],color=10466749,cost=r['cost'],
            baseStats=dict(health=int(s['hp']),attack=int(s['damage']),armor=int(s['armor']),magicResist=int(s['magicResist'])),
            attackRange=int(s['range']),attackIntervalTicks=(200000+speed-1)//speed,baseAttackSpeedBps=speed,
            initialMana=int(s['initialMana']),maxMana=int(s['mana']),abilityId=n+'-ability',traits=c['runtimeTraits'])
        abilities[n+'-ability']=dict(id=n+'-ability',championId=n,name=r['ability']['name'],description=r['ability']['desc'],
            variables={v['name']:[round(x,4) for x in v['value'][1:4]] for v in r['ability']['variables'] if v['value'] is not None})
    header="// Generated by scripts/generate-g2-content.py --g2-2. See normalized/g2-2-*.json.\nimport { freezeContent } from './freeze';\n"
    emit=lambda name,typ,value:f'export const {name}: {typ} = freezeContent('+json.dumps(value,ensure_ascii=False,indent=2)+');\n'
    return {'g2-2-units.ts':header+"import type { UnitDefinition } from '../unit-types';\n"+emit('G22_UNITS','Readonly<Record<string, UnitDefinition>>',units)+emit('G22_MEMBERSHIP','Readonly<Record<string, readonly string[]>>',traits),
        'g2-2-abilities.ts':header+"import type { S13AbilityData } from './abilities';\n"+emit('G22_ABILITIES','Readonly<Record<string, S13AbilityData>>',abilities)+emit('G22_ABILITY_NAMES','Readonly<Record<string,string>>',names)}
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,text in outputs().items():
        path=ROOT/'src/simulation/content'/name
        if a.check:
            if path.read_text()!=text:raise ValueError('Generated output differs: '+name)
        else:path.write_text(text)
